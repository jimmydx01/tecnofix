@register.simple_tag
def ico(nombre, clases='w-5 h-5', grosor='1.8'):
    """Dibuja un ícono SVG que toma el color del texto (currentColor)."""
    trazo = ICONOS.get(nombre, ICONOS['wrench'])
    return format_html(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="{}" stroke-linecap="round" stroke-linejoin="round" class="{}" aria-hidden="true">{}</svg>',
        grosor, clases, mark_safe(trazo),
    )


PALABRAS = (
    ('comput', 'laptop'), ('laptop', 'laptop'), ('portada', 'laptop'), ('celular', 'smartphone'), ('tablet', 'smartphone'),
    ('impres', 'printer'), ('redes', 'wifi'), ('wifi', 'wifi'), ('consola', 'gamepad'), ('gaming', 'gamepad'),
    ('manten', 'sparkles'), ('limpie', 'sparkles'),
)


@register.simple_tag
def ico_servicio(nombre, clases='w-5 h-5', grosor='1.5'):
    """Ícono de respaldo de un servicio según su nombre (si no hay foto o el vínculo falla)."""
    texto = (nombre or '').lower()
    for palabra, icono in PALABRAS:
        if palabra in texto:
            return ico(icono, clases, grosor)
    return ico('wrench', clases, grosor)
